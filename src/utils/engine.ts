/**
 * Calculates slideshow timer interval based on 1-100 pace slider.
 * Speed 1 = 12000ms (12.0s hold)
 * Speed 100 = 600ms (rapid preview)
 */
export function calculateSlideshowInterval(speed: number): number {
  const clamped = Math.max(1, Math.min(100, speed));
  return Math.round(12000 - ((clamped - 1) / 99) * 11400);
}

const BENGALI_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

/**
 * Converts Western Arabic digits (0-9) into authentic Bengali digits (০-৯)
 */
export function toBengaliNumerals(input: string | number): string {
  const str = String(input);
  return str.replace(/[0-9]/g, (digit) => BENGALI_DIGITS[parseInt(digit, 10)]);
}

/**
 * Produces unified CSS filter strings for optical LUT presets and user adjustments
 */
export function getLutFilterCSS(
  preset: LutPreset | string = 'cinematic',
  adjustments?: Partial<FrameAdjustments>
): string {
  const filters: string[] = [];

  const b = adjustments?.brightness ?? 100;
  const c = adjustments?.contrast ?? 100;
  const s = adjustments?.saturation ?? 100;

  if (b !== 100) filters.push(`brightness(${b}%)`);
  if (c !== 100) filters.push(`contrast(${c}%)`);
  if (s !== 100) filters.push(`saturate(${s}%)`);

  switch (preset) {
    case 'noir':
      filters.push('grayscale(1)', 'contrast(140%)', 'brightness(95%)');
      break;
    case 'golden':
      filters.push('sepia(0.35)', 'contrast(115%)', 'saturate(120%)');
      break;
    case 'cyberpunk':
      filters.push('hue-rotate(-25deg)', 'saturate(135%)', 'contrast(115%)');
      break;
    case 'matrix':
      filters.push('hue-rotate(60deg)', 'saturate(125%)', 'contrast(115%)');
      break;
    case 'bleach':
      filters.push('contrast(140%)', 'saturate(50%)');
      break;
    case 'technicolor':
      filters.push('saturate(140%)', 'contrast(115%)');
      break;
    case 'infrared':
      filters.push('hue-rotate(180deg)', 'saturate(140%)', 'contrast(120%)');
      break;
    case 'tungsten':
      filters.push('sepia(0.2)', 'hue-rotate(-15deg)', 'contrast(110%)', 'saturate(110%)');
      break;
    case 'cinematic':
      filters.push('contrast(110%)', 'saturate(115%)', 'sepia(0.08)');
      break;
    case 'raw':
    default:
      break;
  }

  return filters.join(' ') || 'none';
}

/**
 * Filters frames by search query (title, bengaliTitle, tagline, epNumber) and tag
 */
export function filterFrames(
  frames: AnthologyFrame[],
  query: string = '',
  tag?: string
): AnthologyFrame[] {
  if (!Array.isArray(frames)) return [];
  const cleanQ = query.trim().toLowerCase();

  return frames.filter((frame) => {
    if (!frame) return false;
    if (tag && tag.trim()) {
      const matchTag = frame.tags?.some((t) => t.toLowerCase() === tag.toLowerCase());
      if (!matchTag) return false;
    }
    if (!cleanQ) return true;

    const inEp = frame.epNumber?.toLowerCase().includes(cleanQ);
    const inTitle = frame.title?.toLowerCase().includes(cleanQ);
    const inBn = frame.bengaliTitle?.toLowerCase().includes(cleanQ);
    const inTagline = frame.tagline?.toLowerCase().includes(cleanQ);
    const inNotes = frame.directorNotes?.toLowerCase().includes(cleanQ);

    return inEp || inTitle || inBn || inTagline || inNotes;
  });
}

export interface AnthologyStats {
  total: number;
  populated: number;
  percentComplete: number;
  uniqueTags: string[];
}

/**
 * Calculates project completeness stats and unique tags
 */
export function calculateAnthologyStats(frames: AnthologyFrame[]): AnthologyStats {
  if (!Array.isArray(frames) || frames.length === 0) {
    return { total: 0, populated: 0, percentComplete: 0, uniqueTags: [] };
  }
  const total = frames.length;
  const populated = frames.filter((f) => f && (f.imageUrl || f.isVideo)).length;
  const percentComplete = Math.round((populated / total) * 100);

  const tagsSet = new Set<string>();
  frames.forEach((f) => {
    f?.tags?.forEach((t) => tagsSet.add(t));
  });

  return {
    total,
    populated,
    percentComplete,
    uniqueTags: Array.from(tagsSet)
  };
}

/**
 * Generates formatted GitHub Markdown specification for an Anthology project
 */
export function generateProjectMarkdown(project: AnthologyProject): string {
  const lines: string[] = [
    `# ${project.title}`,
    `**Director:** ${project.director} | **Location:** ${project.nodeLocation} | **Aspect Ratio:** ${project.aspectRatio}`,
    `*Generated by RAWx Storyboard Studio on ${project.createdAt} (v${project.version || '1.0'})*`,
    '',
    '| Shot | Title | Bengali | Lens / Optics | Notes |',
    '| :--- | :--- | :--- | :--- | :--- |'
  ];

  (project.frames || []).forEach((f) => {
    const ep = f.epNumber || '000';
    const title = f.title || '';
    const bn = f.bengaliTitle || '';
    const lens = f.cameraSpec?.focalLength || 'Master Cine';
    const notes = (f.directorNotes || f.tagline || '').replace(/\|/g, '-');
    lines.push(`| \`${ep}\` | **${title}** | ${bn} | ${lens} | ${notes} |`);
  });

  return lines.join('\n');
}

/**
 * Generates JSON export string
 */
export function generateProjectJSON(project: AnthologyProject): string {
  return JSON.stringify(project, null, 2);
}

/**
 * Formats a CSV shot list export
 */
export function generateCSVExport(frames: AnthologyFrame[]): string {
  const headers = ['"Episode"', '"Title"', '"Bengali Title"', '"Tagline"', '"Focal Length"', '"Aperture"', '"ISO"', '"Notes"'];
  const rows = (frames || []).map((f) => {
    const ep = `"${(f.epNumber || '').replace(/"/g, '""')}"`;
    const title = `"${(f.title || '').replace(/"/g, '""')}"`;
    const bn = `"${(f.bengaliTitle || '').replace(/"/g, '""')}"`;
    const tag = `"${(f.tagline || '').replace(/"/g, '""')}"`;
    const focal = `"${(f.cameraSpec?.focalLength || '').replace(/"/g, '""')}"`;
    const ap = `"${(f.cameraSpec?.aperture || '').replace(/"/g, '""')}"`;
    const iso = `"${(f.cameraSpec?.iso || '').replace(/"/g, '""')}"`;
    const notes = `"${(f.directorNotes || '').replace(/"/g, '""')}"`;
    return [ep, title, bn, tag, focal, ap, iso, notes].join(',');
  });

  return [headers.join(','), ...rows].join('\n');
}

/**
 * Multi-Layer Zoom Optical Lens Simulation Engine:
 * Computes independent layer transforms for foreground elements (titles, typography, HUD)
 * and background media plate (video/stills).
 * 
 * Supports Hitchcock Vertigo / Dolly Zoom coupling:
 * When vertigoLock is active, background zoom is inversely coupled to foreground zoom,
 * preserving perceived subject size while dramatically stretching or compressing background perspective.
 */
export interface MultiLayerZoomResult {
  bgScale: number;
  fgScale: number;
  bgTransform: string;
  fgTransform: string;
  isVertigo: boolean;
  depthDelta: number;
  depthSeparation: number;
  bgDepthBlur: string;
  fgShadow: string;
  depthFieldLabel: string;
}

export function calculateMultiLayerZoom(
  backgroundZoom: number = 1.0,
  foregroundZoom: number = 1.0,
  vertigoLock: boolean = false
): MultiLayerZoomResult {
  const safeBg = Math.max(0.2, Math.min(3.5, backgroundZoom || 1.0));
  let safeFg = Math.max(0.2, Math.min(3.5, foregroundZoom || 1.0));

  if (vertigoLock && safeBg > 0) {
    // Inverse scaling for Hitchcock dolly zoom effect
    safeFg = Math.max(0.2, Math.min(3.5, 1.0 / safeBg));
  }

  // Optical lens depth separation math
  const depthDelta = safeFg - safeBg;
  const depthSeparation = Math.abs(depthDelta);

  // 3D perspective depth translation along Z axis (pixels in 1000px perspective space)
  const fgZ = Math.round((safeFg - 1.0) * 120);
  const bgZ = Math.round((safeBg - 1.0) * 80);

  // When foreground is closer than background, optical lens simulation introduces
  // shallow depth-of-field background bokeh blur (up to 3.5px)
  let depthBlurPx = 0;
  if (depthDelta > 0.08) {
    depthBlurPx = Math.min(3.5, depthDelta * 2.2);
  }
  const bgDepthBlur = depthBlurPx > 0.1 ? `blur(${depthBlurPx.toFixed(1)}px)` : 'none';

  // Dynamic optical drop-shadow cast by foreground elements onto background plate
  const shadowDist = Math.max(2, Math.round(depthSeparation * 16 + 4));
  const shadowBlur = Math.max(4, Math.round(depthSeparation * 24 + 6));
  const shadowAlpha = Math.min(0.85, Math.max(0.35, depthSeparation * 0.4 + 0.35));
  const fgShadow = `drop-shadow(0 ${shadowDist}px ${shadowBlur}px rgba(0,0,0,${shadowAlpha})) drop-shadow(0 0 16px rgba(212,175,55,0.25))`;

  let depthFieldLabel = 'FLAT 1:1';
  if (depthDelta > 0.35) depthFieldLabel = 'SHALLOW DOF (FG POP)';
  else if (depthDelta < -0.35) depthFieldLabel = 'DEEP FOCUS (BG PUSH)';
  else if (vertigoLock) depthFieldLabel = 'VERTIGO DOLLY LINK';

  return {
    bgScale: safeBg,
    fgScale: safeFg,
    bgTransform: `perspective(1000px) translateZ(${bgZ}px) scale(${safeBg.toFixed(3)})`,
    fgTransform: `perspective(1000px) translateZ(${fgZ}px) scale(${safeFg.toFixed(3)})`,
    isVertigo: vertigoLock,
    depthDelta: Number(depthDelta.toFixed(2)),
    depthSeparation: Number(depthSeparation.toFixed(2)),
    bgDepthBlur,
    fgShadow,
    depthFieldLabel
  };
}
